// Draws text as an amber LED dot-matrix panel, like the price signs on the gantry.
// window.dotMatrix(text, { lit, dim }) returns an SVG string. 5x7 cells, 1-column gap.

(function () {
  "use strict";

  var GLYPHS = {
    "0": ["01110", "10001", "10011", "10101", "11001", "10001", "01110"],
    "1": ["00100", "01100", "00100", "00100", "00100", "00100", "01110"],
    "2": ["01110", "10001", "00001", "00010", "00100", "01000", "11111"],
    "3": ["11111", "00010", "00100", "00010", "00001", "10001", "01110"],
    "4": ["00010", "00110", "01010", "10010", "11111", "00010", "00010"],
    "5": ["11111", "10000", "11110", "00001", "00001", "10001", "01110"],
    "6": ["00110", "01000", "10000", "11110", "10001", "10001", "01110"],
    "7": ["11111", "00001", "00010", "00100", "01000", "01000", "01000"],
    "8": ["01110", "10001", "10001", "01110", "10001", "10001", "01110"],
    "9": ["01110", "10001", "10001", "01111", "00001", "00010", "01100"],
    "$": ["00100", "01111", "10100", "01110", "00101", "11110", "00100"],
    ".": ["00000", "00000", "00000", "00000", "00000", "01100", "01100"],
    ",": ["00000", "00000", "00000", "00000", "01100", "01100", "00100"],
    " ": ["00000", "00000", "00000", "00000", "00000", "00000", "00000"]
  };

  window.dotMatrix = function (text, opts) {
    opts = opts || {};
    var lit = opts.lit || "#ffb000";
    var dim = opts.dim || "rgba(255,176,0,0.10)";
    var chars = String(text).split("");
    var cols = chars.length * 6 - 1;
    var rows = 7;
    var r = 0.42;
    var on = [], off = [];

    chars.forEach(function (ch, ci) {
      var g = GLYPHS[ch] || GLYPHS[" "];
      for (var y = 0; y < rows; y++) {
        for (var x = 0; x < 5; x++) {
          var cx = ci * 6 + x + 0.5, cy = y + 0.5;
          (g[y][x] === "1" ? on : off).push('<circle cx="' + cx + '" cy="' + cy + '" r="' + r + '"/>');
        }
      }
    });

    return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ' + cols + ' ' + rows + '" width="' + cols + '" height="' + rows + '" aria-hidden="true" focusable="false">' +
      '<g fill="' + dim + '">' + off.join("") + '</g>' +
      '<g fill="' + lit + '">' + on.join("") + '</g>' +
      '</svg>';
  };
})();
